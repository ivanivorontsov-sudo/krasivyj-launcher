import json
cat=json.load(open("catalog.json"))
k=["// GENERATED by tools/fonts-src/gen_catalog.py from verified fonts (all 66 Russian letters checked with fontTools).",
"package org.ivanivorontsov.launcher.ui","","import org.ivanivorontsov.launcher.R","import org.ivanivorontsov.launcher.core.FontCategory","",
"data class FontFile(val res: Int, val weight: Int, val variable: Boolean = false)",
"data class FontInfo(val id: String, val name: String, val category: FontCategory, val designer: String, val copyright: String, val unmodified: Boolean, val files: List<FontFile>)","",
"object FontCatalog {","    val all: List<FontInfo> = listOf("]
cm={"handwritten":"HANDWRITTEN","display":"DISPLAY","clean":"CLEAN","mono":"MONO","serif":"SERIF"}
for c in cat:
    files=", ".join(f'FontFile(R.font.{f["res"]}, {f["weight"]}, {str(f.get("variable",False)).lower()})' for f in c["files"])
    cp=c["copyright"].replace("\\","\\\\").replace('"','\\"').replace("$","\\$")
    k.append(f'        FontInfo("{c["id"]}", "{c["name"]}", FontCategory.{cm[c["category"]]}, "{c["designer"]}", "{cp}", {str(c["unmodified"]).lower()}, listOf({files})),')
k+=["    )","    private val byId = all.associateBy { it.id }","    operator fun get(id: String): FontInfo? = byId[id]","}"]
open("../../app/src/main/java/org/ivanivorontsov/launcher/ui/FontCatalog.kt","w").write("\n".join(k)+"\n")
# also the pure id list for unit tests
ids=", ".join(f'"{c["id"]}"' for c in cat)
open("../../app/src/main/java/org/ivanivorontsov/launcher/core/FontIds.kt","w").write(
"// GENERATED. Font ids bundled in res/font (verified Cyrillic).\npackage org.ivanivorontsov.launcher.core\n\nenum class FontCategory(val title: String) { HANDWRITTEN(\"Рукописные\"), DISPLAY(\"Декоративные\"), SERIF(\"С засечками\"), CLEAN(\"Чистые\"), MONO(\"Моно и пиксельные\") }\n\nobject FontIds {\n    val all: Set<String> = setOf("+ids+")\n}\n")
print(len(cat))
