/** 1.3.9: «Лицензии». Data comes from assets/licenses/index.json (generated by tools/licenses/gen_licenses.py from the bundled fonts). */
@Immutable data class LicFont(val family: String, val files: List<String>, val copyright: String, val designer: String, val license: String, val url: String, val text: String)
@Immutable data class LicLib(val name: String, val version: String, val author: String, val license: String, val use: String, val url: String, val text: String, val extra: String?)
@Immutable data class LicIndex(val fontFiles: Int, val fonts: List<LicFont>, val libs: List<LicLib>, val texts: Map<String, String>)

object LicenseData {
    fun load(ctx: Context): LicIndex? = try {
        val o = JSONObject(ctx.assets.open("licenses/index.json").bufferedReader().readText())
        val fonts = o.getJSONArray("fonts").let { a -> (0 until a.length()).map { a.getJSONObject(it) }.map { f ->
            LicFont(f.getString("family"), f.getJSONArray("files").let { fa -> (0 until fa.length()).map { fa.getString(it) } },
                f.optString("copyright"), f.optString("designer"), f.getString("license"), f.optString("licenseUrl"), f.getString("text"))
        } }
        val libs = o.getJSONArray("libraries").let { a -> (0 until a.length()).map { a.getJSONObject(it) }.map { l ->
            LicLib(l.getString("name"), l.optString("version"), l.optString("author"), l.getString("license"), l.optString("use"), l.optString("url"),
                l.getString("text"), l.optString("extra").ifEmpty { null })
        } }
        val t = o.getJSONObject("texts")
        LicIndex(o.optInt("fontFiles", fonts.sumOf { it.files.size }), fonts, libs, t.keys().asSequence().associateWith { t.getString(it) })
    } catch (_: Exception) { null }

    fun text(ctx: Context, index: LicIndex, id: String): String =
        index.texts[id]?.let { f -> try { ctx.assets.open("licenses/$f").bufferedReader().readText() } catch (_: Exception) { null } } ?: ""
}

private fun licenseTitle(id: String) = when (id) {
    "OFL-1.1" -> "SIL Open Font License 1.1"; "Apache-2.0" -> "Apache License 2.0"; "MIT" -> "MIT License"; else -> id
}

/** List of everything bundled; tapping a license opens its full text (state lives in the caller so Back closes the text first). */
@Composable
fun LicensesScreen(openText: String?, onOpenText: (String?) -> Unit) {
    val ctx = LocalContext.current
    val index by produceState<LicIndex?>(null) { value = withContext(Dispatchers.IO) { LicenseData.load(ctx) } }
    val idx = index
    if (idx == null) { Text("Загрузка…", Modifier.padding(16.dp)); return }
    if (openText != null) { LicenseText(idx, openText); return }
    val muted = MaterialTheme.colorScheme.onSurface.copy(alpha = 0.65f)
    LazyColumn(Modifier.fillMaxSize(), contentPadding = PaddingValues(16.dp, 0.dp, 16.dp, 40.dp)) {
        item {
            Text("СуперСмарт использует открытые компоненты. Ниже — все шрифты и библиотеки, которые входят в приложение, с их лицензиями. Нажмите на лицензию, чтобы прочитать полный текст.",
                style = MaterialTheme.typography.bodyMedium, modifier = Modifier.padding(vertical = 4.dp))
            Text("Библиотеки и модели", style = MaterialTheme.typography.titleMedium, modifier = Modifier.padding(top = 16.dp, bottom = 4.dp))
        }
        items(idx.libs, key = { "l" + it.name }) { l ->
            Column(Modifier.fillMaxWidth().padding(vertical = 6.dp)) {
                Text(l.name + if (l.version.isNotEmpty()) "  ${l.version}" else "", style = MaterialTheme.typography.titleSmall)
                Text(listOf(l.author, l.use).filter { it.isNotEmpty() }.joinToString(" · "), fontSize = 12.sp, color = muted)
                Text("Лицензия: " + licenseTitle(l.license) + "  ›", fontSize = 13.sp, color = MaterialTheme.colorScheme.primary,
                    modifier = Modifier.clickable { onOpenText(l.text) }.padding(vertical = 4.dp))
                l.extra?.let { e -> Text("Уведомления о сторонних компонентах  ›", fontSize = 13.sp, color = MaterialTheme.colorScheme.primary,
                    modifier = Modifier.clickable { onOpenText(e) }.padding(vertical = 2.dp)) }
            }
        }
        item {
            Text("Шрифты: ${idx.fonts.size} семейств, ${idx.fontFiles} файлов", style = MaterialTheme.typography.titleMedium, modifier = Modifier.padding(top = 16.dp, bottom = 4.dp))
        }
        items(idx.fonts, key = { "f" + it.family }) { f ->
            Column(Modifier.fillMaxWidth().clickable { onOpenText(f.text) }.padding(vertical = 6.dp)) {
                Text(f.family + if (f.designer.isNotEmpty()) "  —  ${f.designer}" else "", style = MaterialTheme.typography.titleSmall)
                if (f.copyright.isNotEmpty()) Text(f.copyright, fontSize = 11.sp, color = muted)
                Text(licenseTitle(f.license) + "  ·  " + f.files.joinToString(", "), fontSize = 11.sp, color = MaterialTheme.colorScheme.primary)
            }
        }
        item {
            OutlinedButton(onClick = { onOpenText("OFL-1.1") }, modifier = Modifier.padding(top = 12.dp)) { Text("Полный текст SIL OFL 1.1") }
            OutlinedButton(onClick = { onOpenText("Apache-2.0") }, modifier = Modifier.padding(top = 4.dp)) { Text("Полный текст Apache 2.0") }
        }
    }
}

/** Long texts (ThirdPartyNotices is ~330 KB) are split into paragraphs so only visible ones are laid out. */
@Composable
private fun LicenseText(idx: LicIndex, id: String) {
    val ctx = LocalContext.current
    val parts by produceState(emptyList<String>(), id) {
        value = withContext(Dispatchers.IO) { LicenseData.text(ctx, idx, id).split(Regex("\\n\\s*\\n")).filter { it.isNotBlank() } }
    }
    LazyColumn(Modifier.fillMaxSize(), contentPadding = PaddingValues(16.dp, 0.dp, 16.dp, 40.dp)) {
        items(parts.size) { i -> Text(parts[i].trim(), fontSize = 12.sp, lineHeight = 16.sp, modifier = Modifier.padding(vertical = 4.dp)) }
    }
}
